    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        // Validaciones de los campos
        if (txtUsuario.getText().trim().equals("")) {
            JOptionPane.showMessageDialog(this, "Ingrese el usuario");
            txtUsuario.requestFocus();
            return;
        }
        if (new String(txtContrasenia.getPassword()).equals("")) {
            JOptionPane.showMessageDialog(this, "Ingrese la contraseña");
            txtContrasenia.requestFocus();
            return;
        }

        // Recuperando los valores del formulario
        String usuario = txtUsuario.getText().trim();
        String clave = new String(txtContrasenia.getPassword());

        Empleado empleado = SistemaTextil.getGestionEmpleados().autenticar(usuario, clave);
        if (empleado != null) {
            SistemaTextil.setUsuarioActual(empleado);
            frmPrincipal frm = new frmPrincipal(empleado);
            frm.setExtendedState(MAXIMIZED_BOTH);
            frm.setVisible(true);
            dispose();
        } else {
            intentos++;
            txtContrasenia.setText("");
            if (intentos >= INTENTOS_MAXIMOS) {
                JOptionPane.showMessageDialog(this, "Acceso denegado. Superó los " + INTENTOS_MAXIMOS + " intentos.",
                        "Error", JOptionPane.ERROR_MESSAGE);
                System.exit(0);
            }
            JOptionPane.showMessageDialog(this, "Usuario o contraseña incorrectos.\nIntentos restantes: "
                    + (INTENTOS_MAXIMOS - intentos), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnIngresarActionPerformed

